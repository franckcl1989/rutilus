    #[test]
    fn issues_client_certificates_with_the_site_identity() -> Result<(), Box<dyn Error>> {
        let directory = tempfile::tempdir()?;
        let paths = RuntimePaths::from_root(directory.path().join("instance"))?;
        let ca = CenterCa::generate_or_load(&paths)?;
        let site = InstanceId::generate();
        let site_fingerprint = CertificateFingerprint::from_bytes([0xAB; 32]);

        let issued = ca.issue_site_certificate(site, site_fingerprint)?;
        assert_eq!(issued.fingerprint().to_string().split(':').count(), 32);
        assert_eq!(
            x509::subject_common_name(&issued.certificate())?,
            Some(site.to_string())
        );
        assert_eq!(
            x509::site_identity_fingerprint(&issued.certificate())?,
            Some(site_fingerprint)
        );
        // The PEM pair round-trips through the same readers the site uses.
        let (cert_pem, key_pem) = issued.pem_pair();
        let certificate = CertificateDer::from_pem_slice(cert_pem.as_bytes())?;
        let key = PrivateKeyDer::from_pem_slice(key_pem.as_bytes())?;
        assert_eq!(certificate, issued.certificate());
        assert_eq!(key, issued.private_key());
        Ok(())
    }

    /// Runs one full TLS handshake in memory between a client and a server
    /// connection, without sockets, by shuttling each side's write buffer
    /// into the other side's read buffer until neither side is handshaking.
    /// A stalled or failed handshake returns an error instead of looping.
    fn handshake(
        client: &mut ClientConnection,
        server: &mut ServerConnection,
    ) -> Result<(), Box<dyn Error>> {
        let mut buffer = Vec::new();
        for _ in 0..64 {
            let wrote = client.wants_write() || server.wants_write();
            while client.wants_write() {
                buffer.clear();
                client.write_tls(&mut buffer)?;
                server.read_tls(&mut buffer.as_slice())?;
            }
            while server.wants_write() {
                buffer.clear();
                server.write_tls(&mut buffer)?;
                client.read_tls(&mut buffer.as_slice())?;
            }
            client.process_new_packets()?;
            server.process_new_packets()?;
            if !client.is_handshaking() && !server.is_handshaking() {
                return Ok(());
            }
            if !wrote && !client.wants_write() && !server.wants_write() {
                return Err(io::Error::other("the in-memory TLS handshake stalled").into());
            }
        }
        Err(io::Error::other("the in-memory TLS handshake did not complete").into())
    }

    /// A server configuration that requires a client certificate rooted at
    /// the given CA, serving a CA-issued certificate for 127.0.0.1.
    fn verifier_server_config(
        ca: &CenterCa,
        server_identity: ServerCertificate,
    ) -> Result<Arc<ServerConfig>, Box<dyn Error>> {
        let mut roots = RootCertStore::empty();
        roots.add(ca.certificate())?;
        let verifier = WebPkiClientVerifier::builder(Arc::new(roots)).build()?;
        let provider = Arc::new(rustls::crypto::ring::default_provider());
        let config = ServerConfig::builder_with_provider(provider)
            .with_protocol_versions(&[&rustls::version::TLS13])?
            .with_client_cert_verifier(verifier)
            .with_single_cert(vec![server_identity.certificate], server_identity.key)?;
        Ok(Arc::new(config))
    }

    fn verifier_client_config(
        ca: &CenterCa,
        identity: Option<(CertificateDer<'static>, PrivateKeyDer<'static>)>,
    ) -> Result<Arc<rustls::ClientConfig>, Box<dyn Error>> {
        let mut roots = RootCertStore::empty();
        roots.add(ca.certificate())?;
        let provider = Arc::new(rustls::crypto::ring::default_provider());
        let builder = rustls::ClientConfig::builder_with_provider(provider)
            .with_protocol_versions(&[&rustls::version::TLS13])?;
        let config = match identity {
            Some((certificate, key)) => builder
                .with_root_certificates(roots)
                .with_client_auth_cert(vec![certificate], key)?,
            None => builder.with_root_certificates(roots).with_no_client_auth(),
        };
        Ok(Arc::new(config))
    }

    #[tokio::test]
    async fn issued_client_certificates_verify_against_the_ca() -> Result<(), Box<dyn Error>> {
        let directory = tempfile::tempdir()?;
        let paths = RuntimePaths::from_root(directory.path().join("instance"))?;
        let ca = CenterCa::generate_or_load(&paths)?;
        let listen = crate::ListenAddress::parse("127.0.0.1:8443")?;
        let server_identity = ca.issue_server_certificate(&listen)?;
        let site = InstanceId::generate();
        let issued =
            ca.issue_site_certificate(site, CertificateFingerprint::from_bytes([0xCD; 32]))?;

        let server_config = verifier_server_config(&ca, server_identity)?;
        let client_config =
            verifier_client_config(&ca, Some((issued.certificate(), issued.private_key())))?;
        let mut client = ClientConnection::new(client_config, ServerName::try_from("127.0.0.1")?)?;
        let mut server = ServerConnection::new(server_config)?;
        handshake(&mut client, &mut server)?;

        // The server saw the issued certificate, fingerprint and all.
        let presented = server
            .peer_certificates()
            .ok_or_else(|| io::Error::other("no peer certificate"))?;
        let presented = presented
            .first()
            .ok_or_else(|| io::Error::other("empty peer chain"))?;
        assert_eq!(
            CertificateFingerprint::from_certificate_der(presented.as_ref()),
            issued.fingerprint()
        );
        Ok(())
    }

    #[tokio::test]
