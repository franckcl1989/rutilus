    #[test]
    fn generates_persists_and_reuses_the_ca() -> Result<(), Box<dyn Error>> {
        let directory = tempfile::tempdir()?;
        let paths = RuntimePaths::from_root(directory.path().join("instance"))?;

        let first = CenterCa::generate_or_load(&paths)?;
        assert_eq!(first.fingerprint().to_string().split(':').count(), 32);
        assert!(paths.tls_directory().join("center-ca.crt").is_file());
        assert!(paths.tls_directory().join("center-ca.key").is_file());
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(paths.tls_directory().join("center-ca.key"))?
                .permissions()
                .mode()
                & 0o777;
            assert_eq!(mode, 0o600);
        }

        // A second boot reuses the persisted CA identity.
        let second = CenterCa::generate_or_load(&paths)?;
        assert_eq!(first.fingerprint(), second.fingerprint());
        assert_eq!(first.certificate(), second.certificate());
        Ok(())
    }

