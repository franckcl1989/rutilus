//! The Center's certificate authority (design §15, 0.7.0 S3b).
//!
//! The center generates one self-signed CA at first startup and persists
//! it below the data directory's `tls/` folder (`center-ca.crt` and
//! `center-ca.key`, the key mode 0600), so the CA identity survives
//! restarts and every issued certificate stays verifiable. The CA signs:
//!
//! * the center's own server certificate (`center-cert.pem` +
//!   `center-key.pem`, issued for the listen address and persisted by the
//!   acceptor) — the certificate whose SHA-256 fingerprint the operator
//!   pins on the site side (§10.4 explicit trust);
//! * one client certificate per bound site ([`CenterCa::issue_site_certificate`]),
//!   with the site instance id as the subject common name and the site's
//!   own identity fingerprint bound into the product's private-arc
//!   site-identity extension, so the issued certificate is cryptographically
//!   tied to the site instance that requested it.
//!
//! The client certificate's private key is generated by the center and
//! returned to the caller for delivery to the site (the one-time binding
//! flow); the center never persists a site's private key.

use std::{io, time::Duration};

use rcgen::{
    BasicConstraints, CertificateParams, DnType, ExtendedKeyUsagePurpose, IsCa, Issuer, KeyPair,
    KeyUsagePurpose, PKCS_ECDSA_P256_SHA256,
};
use rustls::pki_types::{CertificateDer, PrivateKeyDer, PrivatePkcs8KeyDer};
use rutilus_domain::{CertificateFingerprint, InstanceId};
use rutilus_platform::RuntimePaths;
use thiserror::Error;
use time::OffsetDateTime;

use crate::{
    ListenAddress,
    tls_material::{
        TlsMaterialError, pem_encode, persist_text, read_certificate, read_private_key,
    },
    x509,
};

/// The subject common name of the center CA certificate.
const CENTER_CA_COMMON_NAME: &str = "Rutilus Center CA";

/// The persisted CA file names below the data directory's `tls/` folder.
const CENTER_CA_CERT_FILE: &str = "center-ca.crt";
const CENTER_CA_KEY_FILE: &str = "center-ca.key";

/// Certificate validity windows. The CA lives a decade, like the Site's
/// self-signed pair; the issued certificates live five years. The
/// one-day lookback absorbs clock skew at verification time.
// `Duration::from_days` is not stable in this toolchain, so the day
// multiples below are spelled out in seconds.
#[allow(clippy::duration_suboptimal_units)]
const CA_VALIDITY: Duration = Duration::from_secs(60 * 60 * 24 * 365 * 10);
#[allow(clippy::duration_suboptimal_units)]
const ISSUED_VALIDITY: Duration = Duration::from_secs(60 * 60 * 24 * 365 * 5);
#[allow(clippy::duration_suboptimal_units)]
const NOT_BEFORE_SKEW: Duration = Duration::from_secs(60 * 60 * 24);

/// The center certificate authority: the signing key pair, the CA
/// certificate, and its SHA-256 fingerprint.
#[derive(Debug)]
pub struct CenterCa {
    key_pair: KeyPair,
    certificate: CertificateDer<'static>,
    fingerprint: CertificateFingerprint,
}

impl CenterCa {
    /// Loads the persisted CA pair below `<data>/tls/`, or generates and
    /// persists a fresh CA (the private key mode 0600). A half-written
    /// pair — one file present, the other missing — is a hard error, never
    /// silently regenerated.
    ///
    /// # Errors
    ///
    /// Returns [`CenterCaError`] for unreadable or invalid PEM material,
    /// generation failure, or persistence failure.
    pub fn generate_or_load(paths: &RuntimePaths) -> Result<Self, CenterCaError> {
        let certificate_path = paths.tls_directory().join(CENTER_CA_CERT_FILE);
        let key_path = paths.tls_directory().join(CENTER_CA_KEY_FILE);
        match (
            read_certificate(&certificate_path),
            read_private_key(&key_path),
        ) {
            // A previously generated CA is reused so the center keeps its
            // signing identity — and every issued certificate's validity —
            // across restarts; a missing pair is generated fresh.
            (Ok(certificate), Ok(key)) => Self::from_material(certificate, key),
            (Err(cert_error), Err(key_error))
                if is_missing(&cert_error) && is_missing(&key_error) =>
            {
                Self::generate_and_persist(paths)
            }
            (Err(cert_error), Err(key_error)) => Err(CenterCaError::ReadPair {
                cert_error: Box::new(cert_error),
                key_error: Box::new(key_error),
            }),
            (Err(error), Ok(_)) | (Ok(_), Err(error)) => Err(error.into()),
        }
    }

    /// The CA certificate: the trust anchor of every certificate this
    /// center issues.
    #[must_use]
    pub fn certificate(&self) -> CertificateDer<'static> {
        self.certificate.clone()
    }

    /// The SHA-256 fingerprint of the CA certificate, in the product's
    /// colon-separated uppercase hex format.
    #[must_use]
    pub const fn fingerprint(&self) -> CertificateFingerprint {
        self.fingerprint
    }

    /// Issues one client certificate for a bound site (design §15.1,
    /// one-time binding): the site instance id as the subject common name,
    /// the `clientAuth` extended key usage, and the site's own identity
    /// fingerprint bound into the site-identity extension. The private key
    /// is generated here and returned with the certificate for delivery to
    /// the site; it is never persisted by the center.
    ///
    /// # Errors
    ///
    /// Returns [`CenterCaError`] when the CA subject cannot be read back
    /// for signing, or key or certificate generation fails.
    pub fn issue_site_certificate(
        &self,
        site: InstanceId,
        site_fingerprint: CertificateFingerprint,
    ) -> Result<SiteClientCertificate, CenterCaError> {
        let mut params = issued_certificate_params(&site.to_string())?;
        params.extended_key_usages = vec![ExtendedKeyUsagePurpose::ClientAuth];
        params.key_usages = vec![KeyUsagePurpose::DigitalSignature];
        params
            .custom_extensions
            .push(site_identity_extension(site_fingerprint)?);
        let key_pair = KeyPair::generate().map_err(CenterCaError::GenerateKey)?;
        let certificate = params
            .signed_by(&key_pair, &self.issuer()?)
            .map_err(CenterCaError::Generate)?;
        Ok(SiteClientCertificate::new(
            certificate.der().clone(),
            &key_pair,
        ))
    }

    /// Issues the center's own server certificate for one listen address:
    /// the SAN covers the listen host, the `serverAuth` extended key
    /// usage, and the chain roots at this CA — so a site whose trust
    /// anchor is this CA verifies the center, and the operator's pin of
    /// the server certificate fingerprint is the explicit trust decision
    /// (§10.4).
    ///
    /// # Errors
    ///
    /// Returns [`CenterCaError`] when the CA subject cannot be read back
    /// for signing, or key or certificate generation fails.
    pub(crate) fn issue_server_certificate(
        &self,
        listen: &ListenAddress,
    ) -> Result<ServerCertificate, CenterCaError> {
        let mut params = issued_certificate_params(&listen.to_string())?;
        if let Some(ip) = listen.ip() {
            params.subject_alt_names.push(rcgen::SanType::IpAddress(ip));
        } else {
            let name = rcgen::string::Ia5String::try_from(listen.host())
                .map_err(CenterCaError::Generate)?;
            params.subject_alt_names.push(rcgen::SanType::DnsName(name));
        }
        params.extended_key_usages = vec![ExtendedKeyUsagePurpose::ServerAuth];
        params.key_usages = vec![
            KeyUsagePurpose::DigitalSignature,
            KeyUsagePurpose::KeyEncipherment,
        ];
        let key_pair = KeyPair::generate().map_err(CenterCaError::GenerateKey)?;
        let certificate = params
            .signed_by(&key_pair, &self.issuer()?)
            .map_err(CenterCaError::Generate)?;
        Ok(ServerCertificate {
            certificate: certificate.der().clone(),
            key: PrivatePkcs8KeyDer::from(key_pair.serialize_der()).into(),
        })
    }

    fn from_material(
        certificate: CertificateDer<'static>,
        key: PrivateKeyDer<'static>,
    ) -> Result<Self, CenterCaError> {
        let PrivateKeyDer::Pkcs8(pkcs8) = key else {
            return Err(CenterCaError::UnsupportedKeyFormat);
        };
        let key_pair = KeyPair::from_pkcs8_der_and_sign_algo(&pkcs8, &PKCS_ECDSA_P256_SHA256)
            .map_err(CenterCaError::SigningKey)?;
        let fingerprint = CertificateFingerprint::from_certificate_der(certificate.as_ref());
        Ok(Self {
            key_pair,
            certificate,
            fingerprint,
        })
    }

    fn generate_and_persist(paths: &RuntimePaths) -> Result<Self, CenterCaError> {
        let key_pair = KeyPair::generate().map_err(CenterCaError::GenerateKey)?;
        let mut params =
            CertificateParams::new(Vec::<String>::new()).map_err(CenterCaError::Generate)?;
        params
            .distinguished_name
            .push(DnType::CommonName, CENTER_CA_COMMON_NAME);
        params.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
        params.key_usages = vec![KeyUsagePurpose::KeyCertSign, KeyUsagePurpose::CrlSign];
        set_validity(&mut params, CA_VALIDITY);
        let certificate = params
            .self_signed(&key_pair)
            .map_err(CenterCaError::Generate)?;
        let certificate = certificate.der().clone();
        let fingerprint = CertificateFingerprint::from_certificate_der(certificate.as_ref());
        let certificate_path = paths.tls_directory().join(CENTER_CA_CERT_FILE);
        let key_path = paths.tls_directory().join(CENTER_CA_KEY_FILE);
        persist_text(
            &certificate_path,
            &pem_encode("CERTIFICATE", certificate.as_ref()),
        )?;
        persist_text(
            &key_path,
            &pem_encode("PRIVATE KEY", &key_pair.serialize_der()),
        )?;
        Ok(Self {
            key_pair,
            certificate,
            fingerprint,
        })
    }

    /// The signing issuer: the CA's subject and key. The subject is read
    /// back from the CA certificate (which is the source of truth on every
    /// boot, including a loaded CA) and must be exactly the single common
    /// name this product writes; anything else is refused rather than
    /// signed with.
    fn issuer(&self) -> Result<Issuer<'static, &KeyPair>, CenterCaError> {
        let attributes =
            x509::subject_attributes(&self.certificate).map_err(CenterCaError::Certificate)?;
        let [attribute] = attributes.as_slice() else {
            return Err(CenterCaError::CaSubjectUnsupported);
        };
        if attribute.oid.as_slice() != x509::CN_OID {
            return Err(CenterCaError::CaSubjectUnsupported);
        }
        let mut params =
            CertificateParams::new(Vec::<String>::new()).map_err(CenterCaError::Generate)?;
        params
            .distinguished_name
            .push(DnType::CommonName, attribute.value.as_str());
        Ok(Issuer::new(params, &self.key_pair))
    }
}

fn is_missing(error: &TlsMaterialError) -> bool {
    matches!(
        error,
        TlsMaterialError::ReadFile { source, .. } if source.kind() == io::ErrorKind::NotFound
    )
}

/// The common parameters of every issued certificate: validity window,
/// and the authority key identifier of the signing CA.
fn issued_certificate_params(subject: &str) -> Result<CertificateParams, CenterCaError> {
    let mut params =
        CertificateParams::new(Vec::<String>::new()).map_err(CenterCaError::Generate)?;
    params.distinguished_name.push(DnType::CommonName, subject);
    set_validity(&mut params, ISSUED_VALIDITY);
    Ok(params)
}

fn set_validity(params: &mut CertificateParams, validity: Duration) {
    let now = OffsetDateTime::now_utc();
    params.not_before = now - NOT_BEFORE_SKEW;
    params.not_after = now + validity;
}

/// The site-identity extension: the product's private-arc OID carrying the
/// DER encoding of one OCTET STRING that wraps the site fingerprint bytes.
/// rcgen's `CustomExtension` contract requires the content to be DER, and
/// it is written verbatim into the extension's `extnValue` OCTET STRING.
fn site_identity_extension(
    site_fingerprint: CertificateFingerprint,
) -> Result<rcgen::CustomExtension, CenterCaError> {
    let bytes = site_fingerprint.as_bytes();
    let length = u8::try_from(bytes.len()).map_err(|_| CenterCaError::FingerprintTooLarge)?;
    let mut content = Vec::with_capacity(2 + bytes.len());
    content.push(0x04);
    content.push(length);
    content.extend_from_slice(bytes);
    Ok(rcgen::CustomExtension::from_oid_content(
        x509::SITE_IDENTITY_EXTENSION_OID,
        content,
    ))
}

/// The client certificate of one bound site, with the private key the
/// center generated for it.
///
/// Deliberately not `Debug`: the private key DER must never reach a log.
/// The key is stored as PKCS#8 bytes (the only encoding this product's
/// key generation produces); [`SiteClientCertificate::private_key`]
/// rebuilds a rustls key from those bytes on demand.
pub struct SiteClientCertificate {
    certificate: CertificateDer<'static>,
    key_pkcs8: Vec<u8>,
    fingerprint: CertificateFingerprint,
}

impl SiteClientCertificate {
    fn new(certificate: CertificateDer<'static>, key_pair: &KeyPair) -> Self {
        let fingerprint = CertificateFingerprint::from_certificate_der(certificate.as_ref());
        Self {
            certificate,
            key_pkcs8: key_pair.serialize_der(),
            fingerprint,
        }
    }

    /// The issued client certificate.
    #[must_use]
    pub fn certificate(&self) -> CertificateDer<'static> {
        self.certificate.clone()
    }

    /// The private key of the issued client certificate.
    #[must_use]
    pub fn private_key(&self) -> PrivateKeyDer<'static> {
        PrivatePkcs8KeyDer::from(self.key_pkcs8.clone()).into()
    }

    /// The SHA-256 fingerprint of the issued client certificate — the
    /// identity the center records in its binding and the acceptor maps
    /// back to the site instance.
    #[must_use]
    pub const fn fingerprint(&self) -> CertificateFingerprint {
        self.fingerprint
    }

    /// The certificate and private key as PEM texts, for delivery to the
    /// site (the one-time binding flow writes them below the site's
    /// `tls/` folder).
    #[must_use]
    pub fn pem_pair(&self) -> (String, String) {
        let certificate = pem_encode("CERTIFICATE", self.certificate.as_ref());
        let key = pem_encode("PRIVATE KEY", &self.key_pkcs8);
        (certificate, key)
    }
}

/// The center's own server certificate and key, issued by the center CA.
#[derive(Debug)]
pub(crate) struct ServerCertificate {
    pub(crate) certificate: CertificateDer<'static>,
    pub(crate) key: PrivateKeyDer<'static>,
}

/// A controlled failure while preparing or using the center CA.
#[derive(Debug, Error)]
pub enum CenterCaError {
    #[error("failed to prepare the center CA material: {0}")]
    Material(#[from] TlsMaterialError),
    #[error("failed to read the center CA pair ({cert_error}; {key_error})")]
    ReadPair {
        cert_error: Box<TlsMaterialError>,
        key_error: Box<TlsMaterialError>,
    },
    #[error("the center CA private key is not a PKCS#8 key")]
    UnsupportedKeyFormat,
    #[error("the center CA certificate cannot be read: {0}")]
    Certificate(#[from] x509::DerReadError),
    #[error("the center CA subject is not the single common name this product signs with")]
    CaSubjectUnsupported,
    #[error("failed to generate a center key pair: {0}")]
    GenerateKey(#[source] rcgen::Error),
    #[error("failed to load the center CA signing key: {0}")]
    SigningKey(#[source] rcgen::Error),
    #[error("failed to generate a center certificate: {0}")]
    Generate(#[source] rcgen::Error),
    #[error("the site identity fingerprint does not fit the extension encoding")]
    FingerprintTooLarge,
}

