/// The deterministic self-signed leaf identity of the Mock BMC.
#[derive(Clone, Debug)]
pub struct MockTlsIdentity {
    certificate: CertificateDer<'static>,
    fingerprint: CertificateFingerprint,
}

impl MockTlsIdentity {
    /// Generates the deterministic identity: identical DER, SHA-256
    /// fingerprint, and subject on every call and every run.
    ///
    /// # Errors
    ///
    /// Returns [`MockTlsIdentityError`] when the fixed signing key cannot be
    /// loaded or the fixed certificate parameters cannot be signed.
    pub fn generate() -> Result<Self, MockTlsIdentityError> {
        let mut params =
            CertificateParams::new(vec![String::from("localhost"), String::from("127.0.0.1")])
                .map_err(MockTlsIdentityError::Certificate)?;
        params
            .distinguished_name
            .push(DnType::CommonName, MOCK_COMMON_NAME);
        params.not_before =
            fixed_time(MOCK_NOT_BEFORE_UNIX).map_err(MockTlsIdentityError::Validity)?;
        params.not_after =
            fixed_time(MOCK_NOT_AFTER_UNIX).map_err(MockTlsIdentityError::Validity)?;
        params.serial_number = Some(SerialNumber::from(MOCK_SERIAL));
        let key = KeyPair::from_pkcs8_der_and_sign_algo(
            &PrivatePkcs8KeyDer::from(MOCK_KEY_PKCS8_DER),
            &PKCS_RSA_SHA256,
        )
        .map_err(MockTlsIdentityError::SigningKey)?;
        let certificate = params
            .self_signed(&key)
            .map_err(MockTlsIdentityError::Certificate)?
            .der()
            .clone();
        let fingerprint = CertificateFingerprint::from_certificate_der(certificate.as_ref());
        Ok(Self {
            certificate,
            fingerprint,
        })
    }

    /// Clones the served leaf certificate, for server configuration and
    /// trust construction in tests.
    #[must_use]
    pub fn certificate(&self) -> CertificateDer<'static> {
        self.certificate.clone()
    }

    /// Borrows the DER bytes of the served leaf certificate.
    #[must_use]
    pub fn certificate_der(&self) -> &[u8] {
        self.certificate.as_ref()
    }

    /// Returns the exact SHA-256 identity of the served leaf certificate.
    #[must_use]
    pub const fn fingerprint(&self) -> CertificateFingerprint {
        self.fingerprint
    }

    /// Returns the Pin text in the product's canonical `CertificateFingerprint`
    /// format (colon-separated uppercase SHA-256 bytes).
    #[must_use]
    pub fn fingerprint_text(&self) -> String {
        self.fingerprint.to_string()
    }

    /// Builds the Rustls server configuration that serves this identity.
    pub(crate) fn server_config(&self) -> Result<ServerConfig, MockBmcError> {
        let provider = Arc::new(default_provider());
        ServerConfig::builder_with_provider(provider)
            .with_safe_default_protocol_versions()
            .map_err(MockBmcError::TlsConfiguration)?
            .with_no_client_auth()
            .with_single_cert(
                vec![self.certificate.clone()],
                PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(MOCK_KEY_PKCS8_DER)),
            )
            .map_err(MockBmcError::TlsConfiguration)
    }
}

/// Converts one fixed UNIX timestamp into the certificate validity instant.
///
/// The timestamp is a compile-time constant, so this can only fail if the
/// constant itself is out of the `OffsetDateTime` range.
fn fixed_time(unix_timestamp: i64) -> Result<OffsetDateTime, time::error::ComponentRange> {
    OffsetDateTime::from_unix_timestamp(unix_timestamp)
}

/// A controlled failure while generating the deterministic mock identity.
#[derive(Debug, Error)]
pub enum MockTlsIdentityError {
    /// The fixed certificate parameters could not be signed.
    #[error("the deterministic mock certificate could not be generated: {0}")]
    Certificate(#[source] rcgen::Error),
    /// The fixed signing key could not be loaded from its embedded DER.
    #[error("the fixed mock signing key could not be loaded: {0}")]
    SigningKey(#[source] rcgen::Error),
    /// A fixed validity timestamp is outside the representable range.
    #[error("the fixed mock certificate validity is out of range: {0}")]
    Validity(#[source] time::error::ComponentRange),
}
