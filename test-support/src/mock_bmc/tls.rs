//! Deterministic TLS identity for the Mock BMC.
//!
//! A demo must show the same fingerprint every time it runs, so the leaf
//! certificate is fully deterministic: a fixed RSA-2048 key, a fixed subject
//! common name, a fixed serial number, and fixed validity bounds. RSA is used
//! because ring's ECDSA signing draws a random nonce per signature, which
//! would change the certificate DER -- and the SHA-256 fingerprint the
//! product pins -- on every run; PKCS#1 v1.5 RSA signatures are
//! deterministic, so the DER bytes are identical on every run.

use std::sync::Arc;

use rcgen::{CertificateParams, DnType, KeyPair, PKCS_RSA_SHA256, SerialNumber};
use rutilus_domain::CertificateFingerprint;
use thiserror::Error;
use time::OffsetDateTime;
use tokio_rustls::rustls::{
    ServerConfig,
    crypto::ring::default_provider,
    pki_types::{CertificateDer, PrivateKeyDer, PrivatePkcs8KeyDer},
};

use super::MockBmcError;

